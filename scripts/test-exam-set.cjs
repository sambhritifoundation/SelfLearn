const fs=require('node:fs'),path=require('node:path'),http=require('node:http'),assert=require('node:assert/strict');
const modules=path.join(process.env.USERPROFILE,'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules');
const {chromium}=require(path.join(modules,'playwright'));
const root=path.resolve(__dirname,'..');
const server=http.createServer((req,res)=>{const file=path.join(root,decodeURIComponent(req.url.split('?')[0])||'index.html');fs.readFile(file,(error,data)=>{if(error){res.writeHead(404);return res.end()}res.setHeader('Content-Type',path.extname(file)==='.js'?'text/javascript':path.extname(file)==='.css'?'text/css':'text/html');res.end(data)})});
(async()=>{
  await new Promise(resolve=>server.listen(8767,'127.0.0.1',resolve));
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  try{
    const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[],deliveries=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.route('https://formsubmit.co/**',async route=>{deliveries.push(route.request());await route.fulfill({status:200,contentType:'text/html',body:'<!doctype html><title>Accepted</title>'})});
    await page.goto('http://127.0.0.1:8767/examprep.html');
    assert.equal(await page.locator('[data-exam]').count(),2);
    await page.locator('[data-exam^="SL-EXAM-C10-SCI-CRE-"]').click();
    assert(await page.locator('#exam-fields').isVisible());
    assert.equal(await page.locator('#delivery-email').getAttribute('required'),null);
    assert.equal(await page.locator('#setup>details').getAttribute('open'),'');
    await page.locator('#student').fill('Test Student');
    await page.locator('#student-id').fill('ROLL-101');
    await page.locator('#delivery-email').fill('teacher@example.org');
    await page.getByText('First time sending to this examiner?',{exact:true}).click();
    await page.locator('#activate-email').click();
    await page.locator('#activation-status').getByText(/Check teacher@example.org/).waitFor({timeout:5000});
    assert.equal(deliveries.length,1);
    assert(decodeURIComponent((deliveries[0].postData()||'').replace(/\+/g,' ')).includes('Activate SelfLearn ExamPrep PDF delivery'));
    await page.locator('#setup button:not([type="button"])').click();
    assert.equal(await page.locator('.exam-home').count(),1);
    await page.locator('#begin-exam').click();
    assert.equal(await page.locator('#palette button').count(),39);
    assert((await page.locator('.note').textContent()).includes('Test Student'));
    await page.addScriptTag({path:path.join(modules,'pdf-lib/dist/pdf-lib.min.js')});
    await page.locator('input[name=answer][value="C"]').check();
    await page.locator('#palette button').nth(9).click();
    await page.locator('#written').fill('2Al + 6HCl → 2AlCl3 + 3H2. The balanced equation has equal atoms on both sides.');
    await page.locator('#submit').click();
    await page.locator('#delivery-status.pending').waitFor({timeout:30000});
    assert((await page.locator('#provisional-summary').textContent()).includes('Needs teacher review'));
    assert((await page.locator('#provisional-summary').textContent()).includes('3/80'));
    assert((await page.locator('.rubric-score').nth(1).textContent()).includes('2/2'));
    assert.equal(deliveries.length,2);
    assert(!deliveries[1].url().includes('/ajax/'));
    assert(deliveries[1].url().includes(encodeURIComponent('teacher@example.org')));
    assert((deliveries[1].headers()['content-type']||'').includes('multipart/form-data'));
    const payload=deliveries[1].postData();
    assert(payload.includes('SelfLearn Exam'));
    assert(payload.includes('Test Student'));
    assert(payload.includes('ROLL-101'));
    assert(payload.includes('SL-EXAM-C10-SCI-CRE-'));
    assert(payload.includes('application/pdf'));
    assert(payload.includes('.pdf'));
    assert.equal(await page.locator('#download-pdf').count(),1);
    assert.equal(await page.locator('#retry-email').count(),1);
    await page.locator('#retry-email').click();
    await page.locator('#delivery-status.pending').waitFor({timeout:30000});
    assert.equal(deliveries.length,3);
    assert.deepEqual(errors,[]);
    console.log('PASS: pre-test email activation, native multipart PDF attachment, identifying subject, download fallback, and resend verified.');
  }finally{await browser.close();server.close()}
})().catch(error=>{console.error(error);server.close();process.exitCode=1});
